package profile

import (
	"errors"
	"fmt"
	"sort"
	"strings"
)

// UnitName is the systemd unit SparkRoster writes for a launched profile.
func UnitName(id string) string { return "spark-roster-" + id + ".service" }

// ContainerName is the docker container a launched docker profile runs as.
func ContainerName(id string) string { return "spark-roster-" + id }

// systemdQuote quotes one word for a command line. systemd expands $VARIABLES in both
// places this is used, so $ is always doubled. It expands % specifiers only when it reads
// a unit file, not in a property passed to systemd-run: a transient property keeps %%
// literally (measured on the GX10, 2026-11-25). specifiers says which case this is.
func systemdQuote(s string, specifiers bool) string {
	pairs := []string{`\`, `\\`, `"`, `\"`, `$`, `$$`}
	if specifiers {
		pairs = append(pairs, `%`, `%%`)
	}
	return `"` + strings.NewReplacer(pairs...).Replace(s) + `"`
}

// QuoteExec joins argv into one command line for a transient property such as
// ExecStopPost passed to systemd-run. Unit files use systemdQuote with specifiers.
func QuoteExec(argv []string) string {
	words := make([]string, len(argv))
	for i, w := range argv {
		words[i] = systemdQuote(w, false)
	}
	return strings.Join(words, " ")
}

func noControl(s string) bool { return !strings.ContainsAny(s, "\r\n\x00") }

// RenderUnit builds the systemd unit for a launched profile. The unit starts
// the service in the foreground so systemd owns its lifecycle, and it never
// restarts on its own: SparkRoster decides when a profile runs.
func RenderUnit(p Profile, user, group string) (string, error) {
	if err := p.Validate(); err != nil {
		return "", err
	}
	if p.Launch == nil {
		return "", errors.New("only launched profiles have a generated unit")
	}
	if !userName(user) || !userName(group) {
		return "", errors.New("invalid user or group name")
	}
	l := *p.Launch
	var argv []string
	switch l.Runtime {
	case "docker":
		argv = []string{"/usr/bin/docker", "run", "--rm", "--name", ContainerName(p.ID), "--gpus", "all", "--network", "host"}
		if l.MemoryLimit != "" {
			if !memoryLimit(l.MemoryLimit) {
				return "", fmt.Errorf("invalid memory_limit %q", l.MemoryLimit)
			}
			argv = append(argv, "--memory", l.MemoryLimit, "--memory-swap", l.MemoryLimit)
		}
		keys := make([]string, 0, len(l.Env))
		for k := range l.Env {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		for _, k := range keys {
			argv = append(argv, "-e", k+"="+l.Env[k])
		}
		argv = append(argv, l.DockerArgs...)
		for _, m := range l.Mounts {
			argv = append(argv, "--mount", dockerMount(m))
		}
		argv = append(argv, l.Image)
	case "process":
		argv = []string{l.Exe}
	}
	argv = append(argv, l.Args...)
	var words []string
	for _, w := range argv {
		if !noControl(w) {
			return "", errors.New("launch arguments must not contain control characters")
		}
		words = append(words, systemdQuote(w, true))
	}
	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by spark-roster for profile %s. Edits are overwritten.\n", p.ID)
	after := "network-online.target"
	if l.Runtime == "docker" {
		after += " docker.service"
	}
	fmt.Fprintf(&b, "[Unit]\nDescription=SparkRoster profile %s\nAfter=%s\nWants=network-online.target\n", p.ID, after)
	if l.Runtime == "docker" {
		b.WriteString("Requires=docker.service\n")
	}
	fmt.Fprintf(&b, "\n[Service]\nType=simple\nUser=%s\nGroup=%s\n", user, group)
	if l.Runtime == "docker" {
		fmt.Fprintf(&b, "ExecStartPre=-/usr/bin/docker rm -f %s\n", ContainerName(p.ID))
		fmt.Fprintf(&b, "ExecStop=-/usr/bin/docker stop -t 20 %s\n", ContainerName(p.ID))
		b.WriteString("SuccessExitStatus=137 143\n")
	}
	b.WriteString("ExecStart=" + strings.Join(words, " ") + "\n")
	b.WriteString("Restart=no\nTimeoutStopSec=60\n")
	if l.Runtime == "process" {
		b.WriteString("KillMode=control-group\n")
		if l.MemoryLimit != "" {
			if !memoryLimit(l.MemoryLimit) {
				return "", fmt.Errorf("invalid memory_limit %q", l.MemoryLimit)
			}
			fmt.Fprintf(&b, "MemoryMax=%s\nMemorySwapMax=0\n", strings.ToUpper(l.MemoryLimit))
		}
	}
	return b.String(), nil
}

func userName(s string) bool {
	if s == "" || len(s) > 64 || s == "root" {
		return false
	}
	for i, r := range s {
		ok := r == '_' || (r >= 'a' && r <= 'z') || (i > 0 && (r == '-' || (r >= '0' && r <= '9')))
		if !ok {
			return false
		}
	}
	return true
}

func memoryLimit(s string) bool {
	if len(s) < 2 || len(s) > 8 {
		return false
	}
	last := s[len(s)-1]
	if last != 'g' && last != 'm' {
		return false
	}
	for _, r := range s[:len(s)-1] {
		if r < '0' || r > '9' {
			return false
		}
	}
	return s[0] != '0'
}

// dockerMount turns "src:dst[:ro|rw]" into docker's --mount syntax, which
// does not create a missing source the way -v does.
func dockerMount(m string) string {
	parts := strings.Split(m, ":")
	out := "type=bind,src=" + parts[0] + ",dst=" + parts[1]
	if len(parts) == 3 && parts[2] == "ro" {
		out += ",readonly"
	}
	return out
}
